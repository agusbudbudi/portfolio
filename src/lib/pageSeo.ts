// Per-page SEO + social-share copy for the static public pages. One source
// for both renderers:
//   - the SPA, via <Seo {...pageSeo('/path')} /> (react-helmet-async), and
//   - api/qa-library-og.ts (?type=page), which serves these tags to social
//     preview bots that never run JS (WhatsApp, LinkedIn, Facebook, X, ...).
// Keep free of browser-only imports.
//
// `title` / `description` are the search-result copy (keyword-led);
// `shareTitle` / `shareDescription` are the og:/twitter: copy people see
// when a link is pasted into a chat, written to be read rather than ranked.
// Images are 1200×630 PNGs generated by `npm run og:build`
// (scripts/og/build.tsx → public/shared/img/og/<image>.png).

import { MENTORING_PLANS } from '../features/mentoring/data/pricingPlans.js';

export const SITE_URL = 'https://www.mentorqa.com';

const priceValue = (p: string) => Number(p.replace(/\D/g, ''));
/** Cheapest mentoring price, e.g. "Rp99.000". */
export const LOWEST_MENTORING_PRICE = MENTORING_PLANS.reduce(
  (min, p) => (priceValue(p.price) < priceValue(min) ? p.price : min),
  MENTORING_PLANS[0].price,
);

/** Bump after regenerating images so chat apps drop their cached preview. */
const OG_VERSION = 1;

export type OgImageName =
  | 'home'
  | 'courses'
  | 'qa-simulator'
  | 'qa-library'
  | 'portfolio'
  | 'mentoring'
  | 'mentoring-booking'
  | 'programs'
  | 'career-path'
  | 'personal-portfolio'
  | 'personal-about'
  | 'personal-projects'
  | 'personal-certifications';

export function ogImageUrl(name: OgImageName): string {
  return `${SITE_URL}/shared/img/og/${name}.png?v=${OG_VERSION}`;
}

export const DEFAULT_OG_IMAGE = ogImageUrl('home');

export interface PageSeo {
  path: string;
  title: string;
  description: string;
  shareTitle: string;
  shareDescription: string;
  image: string;
  /** Kept out of search: read by <Seo> in the app and by the crawler HTML. */
  noindex?: boolean;
}

export type PageSeoPath =
  | '/'
  | '/courses'
  | '/qa-simulator'
  | '/qa-library'
  | '/portfolio'
  | '/mentoring'
  | '/mentoring/booking'
  | '/programs'
  | '/career-path'
  | '/personal-portfolio'
  | '/personal-portfolio/about'
  | '/personal-portfolio/projects'
  | '/personal-portfolio/certifications';

const page = (path: PageSeoPath, image: OgImageName, copy: Omit<PageSeo, 'path' | 'image'>): PageSeo => ({
  path,
  image: ogImageUrl(image),
  ...copy,
});

