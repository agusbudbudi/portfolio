export function pageSeo(path: PageSeoPath): PageSeo {
  return PAGE_SEO[path];
}

/** Bot lookup: '' and '/x/' normalise to their canonical key. */
export function findPageSeo(path: string): PageSeo | null {
  const key = (`/${path}`.replace(/\/+/g, '/').replace(/(.)\/$/, '$1')) as PageSeoPath;
  return PAGE_SEO[key] ?? null;
}
